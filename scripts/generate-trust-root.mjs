#!/usr/bin/env node
/**
 * One-shot generator for src/confer/noise/trust-root.ts.
 * Reads public trust-root material out of the gitignored extracted modules
 * and emits typed constants. Run manually after re-captures; never commit
 * captures/ itself.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const read = (f) => readFileSync(`captures/metro-modules/${f}`, 'utf8');
const evalLiteral = (src, label) => {
  const value = new Function(`return (${src})`)();
  if (!value) throw new Error(`${label}: empty literal`);
  return value;
};

// --- INTEL_TRUST_AUTHORITY_JWKS (module 2106) ---
const jwksLine = read('2106-intel-trust-authority-jwks.js');
const jwksStart = jwksLine.indexOf('const A=');
const jwksEnd = jwksLine.lastIndexOf('},2106,[');
if (jwksStart === -1 || jwksEnd === -1) throw new Error('JWKS bounds not found');
const jwks = evalLiteral(jwksLine.slice(jwksStart + 'const A='.length, jwksEnd), 'JWKS');

// --- MRTD allowlist (module 2037) ---
const tdxLine = read('2037-tdx-attestation-validator.js');
const mrtdMatch = tdxLine.match(/const a=(\[[^\]]*\])/);
if (!mrtdMatch) throw new Error('MRTD allowlist not found');
const mrtd = evalLiteral(mrtdMatch[1], 'MRTD');

// --- Sigstore identity (module 1935) ---
const c1935 = read('1935-auth-constants.js');
const idMatch = c1935.match(
  /const t='https:\/\/confer\.to',n='https:\/\/api\.confer\.to',o='[^']*',s="([^"]*)",c='([^']*)',l=(!?[a-z01]+)/,
);
if (!idMatch) throw new Error('sigstore identity not found');
const [, email, issuer, staging] = idMatch;

// --- Production trusted root (module 2038) ---
const rootLine = read('2038-sigstore-root-production.js');
const rootStart = rootLine.indexOf('t.exports={');
const rootEnd = rootLine.lastIndexOf(',2038,[');
if (rootStart === -1 || rootEnd === -1) throw new Error('trusted root bounds not found');
// The character immediately before ",2038,[" is the module factory's own "}".
const root = evalLiteral(rootLine.slice(rootStart + 't.exports='.length, rootEnd - 1), 'root');

const banner = `/**
 * Pinned public trust-root material for confer.to TDX attestation validation.
 *
 * Generated by scripts/generate-trust-root.mjs from gitignored extracted
 * modules of entry-ebca9276d77e452faa3c6dfcfa0fd7b8.js:
 *   - INTEL_TRUST_AUTHORITY_JWKS  <- module 2106
 *   - EXPECTED_MRTD_ALLOWLIST     <- module 2037
 *   - SIGSTORE_EMAIL / _ISSUER    <- module 1935 ("../auth/constants")
 *   - PRODUCTION_TRUSTED_ROOT     <- module 2038
 *
 * These are PUBLIC trust anchors (verification keys and certificate roots),
 * not secrets. Re-generate this file whenever a new frontend bundle is
 * captured; a mismatch should surface as UPSTREAM_PROTOCOL_CHANGED.
 */

`;

const body = `export const INTEL_TRUST_AUTHORITY_JWKS = ${JSON.stringify(jwks, null, 2)} as const;

/** Known-good TDX MRTD firmware digests (hex, lowercase-insensitive compare). */
export const EXPECTED_MRTD_ALLOWLIST: readonly string[] = ${JSON.stringify(mrtd, null, 2)};

export const SIGSTORE_EMAIL = ${JSON.stringify(email)};
export const SIGSTORE_ISSUER = ${JSON.stringify(issuer)};

/** The browser build pins production; staging was compiled out (l=${staging}). */
export const PRODUCTION_TRUSTED_ROOT = ${JSON.stringify(root, null, 2)} as const;
`;

writeFileSync('src/confer/noise/trust-root.ts', banner + body);
console.log(
  'trust-root.ts written:',
  jwks.keys.length,
  'JWKS keys |',
  mrtd.length,
  'MRTD entries |',
  email,
  '|',
  issuer,
);
